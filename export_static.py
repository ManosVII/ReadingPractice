"""Export the reading passages to docs/texts.js for the browser-only version.

The browser version (docs/) runs on GitHub Pages without a server, so the
texts are shipped as a static file. Run this again after re-extracting:

    python export_static.py                 # reads data/reading_new.db
    python export_static.py --db data/reading.db
"""
import argparse
import json
import sqlite3
from pathlib import Path

ROOT = Path(__file__).parent


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default=str(ROOT / "data" / "reading_new.db"))
    ap.add_argument("--out", default=str(ROOT / "docs" / "texts.js"))
    args = ap.parse_args()

    con = sqlite3.connect(args.db)
    con.row_factory = sqlite3.Row
    rows = con.execute(
        "SELECT id, source_id, title, content, word_count, page_number, chapter "
        "FROM texts ORDER BY source_id, page_number, id"
    ).fetchall()
    con.close()

    texts = [dict(r) for r in rows]
    payload = json.dumps(texts, ensure_ascii=False, separators=(",", ":"))
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        "// Generated by export_static.py from the texts table. Do not edit by hand.\n"
        f"window.TEXTS = {payload};\n",
        encoding="utf-8",
    )
    print(f"{len(texts)} texts -> {out}")


if __name__ == "__main__":
    main()
